/**
 * Значение заголовка авторизации ЛЮБОЙ схемы: необязательная схема словом и
 * учётные данные одним словом без `=` и `,` внутри (кроме дополнения base64):
 * `ApiKey …`, `HMAC …`, `SSWS …`, сырой токен без схемы. `Digest username="…",
 * realm=…` — список параметров, а не одно значение: не подходит.
 */
export const AUTH_HEADER_VALUE = /^(?:(?<scheme>[A-Za-z][\w-]*)\s+)?(?<credential>[^\s,=]+={0,2})$/u;
